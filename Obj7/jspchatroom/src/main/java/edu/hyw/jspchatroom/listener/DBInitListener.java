package edu.hyw.jspchatroom.listener;

import edu.hyw.jspchatroom.dao.UserDao;
import edu.hyw.jspchatroom.util.DBUtil;
import jakarta.servlet.ServletContext;
import jakarta.servlet.ServletContextEvent;
import jakarta.servlet.ServletContextListener;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * DBInitListener —— 数据库初始化监听器（实验 07 步骤 2）。
 *
 * <p>Web 应用启动时自动执行：</p>
 * <ol>
 *   <li>检查数据库连接：H2 文件模式下，数据文件不存在时会自动创建；</li>
 *   <li>检查 users / messages 表是否存在，不存在则执行建表 DDL；</li>
 *   <li>把所有用户的在线状态清零（重启后内存会话已丢失，避免脏数据）；</li>
 *   <li>在控制台打印初始化日志，方便课堂上确认结果。</li>
 * </ol>
 *
 * <p>初始化只需在首次运行时真正建表；之后每次启动都执行
 * “先判断存在性、再决定是否建表”，因此不会重复建表、也不会清空历史数据。</p>
 *
 * <p>控制台预期输出：</p>
 * <pre>
 *   🔄 初始化数据库...
 *   ✅ 数据库初始化完成！
 * </pre>
 */
public class DBInitListener implements ServletContextListener {

    /** 用户表建表语句。 */
    private static final String DDL_USERS = """
            CREATE TABLE IF NOT EXISTS users (
                id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username      VARCHAR(50)  NOT NULL,
                password      VARCHAR(200) NOT NULL,
                created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
                last_login_at TIMESTAMP,
                online        BOOLEAN      NOT NULL DEFAULT FALSE,
                CONSTRAINT uk_users_username UNIQUE (username)
            )
            """;

    /** 消息表建表语句：user_id 外键关联 users(id)。 */
    private static final String DDL_MESSAGES = """
            CREATE TABLE IF NOT EXISTS messages (
                id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id    INT          NOT NULL,
                content    VARCHAR(500) NOT NULL,
                created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT fk_messages_user FOREIGN KEY (user_id)
                    REFERENCES users (id) ON DELETE CASCADE
            )
            """;

    /** 按发送时间排序的索引，让“取最近 N 条”更快。 */
    private static final String DDL_INDEX =
            "CREATE INDEX IF NOT EXISTS idx_messages_created_at ON messages (created_at)";

    @Override
    public void contextInitialized(ServletContextEvent sce) {
        ServletContext app = sce.getServletContext();
        System.out.println("🔄 初始化数据库...");
        try {
            // 1. 连接自检：文件不存在时 H2 会自动创建 .mv.db 文件
            if (!DBUtil.testConnection()) {
                throw new SQLException("数据库连接失败: " + DBUtil.getUrl());
            }
            System.out.println("[DBInitListener] 数据库连接成功: " + DBUtil.getUrl());
            System.out.println("[DBInitListener] 数据库文件: " + DBUtil.getDatabaseFilePath());

            // 2. 建表（不存在才建，重复执行是安全的）
            try (Connection c = DBUtil.getConnection()) {
                boolean usersExists = tableExists(c, "USERS");
                boolean messagesExists = tableExists(c, "MESSAGES");

                if (!usersExists) {
                    execute(c, DDL_USERS);
                    System.out.println("[DBInitListener] 已创建表 users");
                } else {
                    System.out.println("[DBInitListener] 表 users 已存在，跳过建表");
                }

                if (!messagesExists) {
                    execute(c, DDL_MESSAGES);
                    System.out.println("[DBInitListener] 已创建表 messages");
                } else {
                    System.out.println("[DBInitListener] 表 messages 已存在，跳过建表");
                }

                execute(c, DDL_INDEX);
            }

            // 3. 重启后没有任何会话，把在线状态统一清零
            int reset = new UserDao().resetAllOnline();
            if (reset > 0) {
                System.out.println("[DBInitListener] 已重置 " + reset + " 个用户的在线状态");
            }

            // 4. 把初始化结果放进 application 作用域，页面可以据此提示
            app.setAttribute("dbReady", Boolean.TRUE);
            app.setAttribute("dbUrl", DBUtil.getUrl());
            app.setAttribute("dbFile", DBUtil.getDatabaseFilePath());
            System.out.println("✅ 数据库初始化完成！");
        } catch (Exception e) {
            app.setAttribute("dbReady", Boolean.FALSE);
            app.setAttribute("dbError", e.getMessage());
            // 打印完整堆栈，方便定位 SQL 语法错误、文件被占用等问题
            System.err.println("❌ 数据库初始化失败: " + e.getMessage());
            e.printStackTrace();
        }
    }

    @Override
    public void contextDestroyed(ServletContextEvent sce) {
        System.out.println("[DBInitListener] Web 应用已停止，数据库文件保留在磁盘上，下次启动可继续使用");
    }

    /** 判断某张表是否已经存在（H2 的元数据表 INFORMATION_SCHEMA.TABLES）。 */
    private boolean tableExists(Connection c, String tableName) throws SQLException {
        String sql = "SELECT 1 FROM INFORMATION_SCHEMA.TABLES "
                + "WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = ?";
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, tableName);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next();
            }
        }
    }

    /** 执行一条 DDL。 */
    private void execute(Connection c, String sql) throws SQLException {
        try (Statement st = c.createStatement()) {
            st.execute(sql);
        }
    }
}
